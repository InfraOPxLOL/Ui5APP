import ObjectStatus from "sap/m/ObjectStatus";
import { severityToValueState, type SeverityValue } from "../../core/constants/Severity";

/**
 * Reusable severity badge.
 *
 * A thin specialization of {@link sap.m.ObjectStatus} that renders an alert/health severity with
 * the correct semantic colour derived once from {@link severityToValueState}. Every place a
 * severity is shown (Alert Notification, Dashboard, Live Monitoring) uses this control rather than
 * ad-hoc `ObjectStatus` markup, so severity colouring is defined in exactly one place.
 *
 * The runtime property accessors (`getSeverity`/`setSeverity`) are generated by UI5 from the
 * metadata below; their TypeScript signatures are declared in the companion `SeverityBadge.gen.d.ts`.
 *
 * @namespace com.middlewareops.integrationportal.library.controls
 */
export default class SeverityBadge extends ObjectStatus {
  // Reuses the parent's renderer verbatim since this control adds no custom rendering — without
  // this, UI5 tries to auto-load a nonexistent "SeverityBadgeRenderer" module.
  public static readonly renderer = "sap.m.ObjectStatusRenderer";

  public static readonly metadata = {
    properties: {
      /** The severity value to render (see {@link SeverityValue}). */
      severity: { type: "string", defaultValue: "INFO" },
    },
  };

  /**
   * Applies the severity, updating the underlying object status' semantic state.
   * @param severity the severity value.
   * @returns this control, for chaining.
   */
  public setSeverity(severity: SeverityValue): this {
    this.setProperty("severity", severity, true);
    this.setState(severityToValueState(severity));
    return this;
  }
}
