import ObjectStatus from "sap/m/ObjectStatus";
import StatusFormatter from "../../core/formatters/StatusFormatter";

/**
 * Domain of a {@link StatusIndicator}, selecting which status→colour/icon mapping to apply.
 */
export type StatusDomain = "message" | "queue";

/**
 * Reusable status indicator.
 *
 * A specialization of {@link sap.m.ObjectStatus} that renders a domain status value (MPL message
 * status or JMS queue status) with the correct semantic colour and icon, resolved once through
 * {@link StatusFormatter}. Used everywhere a "failed / completed / retry" style status is shown.
 *
 * Runtime accessors are generated by UI5 from the metadata; their signatures live in the companion
 * `StatusIndicator.gen.d.ts`.
 *
 * @namespace com.middlewareops.integrationportal.library.controls
 */
export default class StatusIndicator extends ObjectStatus {
  // Reuses the parent's renderer verbatim since this control adds no custom rendering — without
  // this, UI5 tries to auto-load a nonexistent "StatusIndicatorRenderer" module.
  public static readonly renderer = "sap.m.ObjectStatusRenderer";

  public static readonly metadata = {
    properties: {
      /** Raw domain status value (e.g. `FAILED`, `NEAR_CAPACITY`). */
      statusValue: { type: "string", defaultValue: "" },
      /** Which status domain the value belongs to. */
      domain: { type: "string", defaultValue: "message" },
      /** Whether to render the mapped icon. */
      showIcon: { type: "boolean", defaultValue: true },
    },
  };

  /**
   * Sets the status value and refreshes the derived colour/icon.
   * @param value the raw status value.
   * @returns this control, for chaining.
   */
  public setStatusValue(value: string): this {
    this.setProperty("statusValue", value, true);
    this.refresh();
    return this;
  }

  /**
   * Sets the status domain and refreshes the derived colour/icon.
   * @param domain the status domain.
   * @returns this control, for chaining.
   */
  public setDomain(domain: StatusDomain): this {
    this.setProperty("domain", domain, true);
    this.refresh();
    return this;
  }

  private refresh(): void {
    const value = this.getProperty("statusValue") as string;
    const domain = this.getProperty("domain") as StatusDomain;
    if (domain === "queue") {
      this.setState(StatusFormatter.queueStatusState(value));
    } else {
      this.setState(StatusFormatter.messageStatusState(value));
      if (this.getProperty("showIcon") === true) {
        this.setIcon(StatusFormatter.messageStatusIcon(value));
      }
    }
  }
}
